import {z} from 'zod';

/** Stage 6: a vision model critiques renders of the real 3D house; findings feed bounded edits. */
export const reviewSchema = z.object({
  scores: z.object({massing: z.number().min(1).max(10), roofs: z.number().min(1).max(10), entrance: z.number().min(1).max(10), glazing: z.number().min(1).max(10), outdoor: z.number().min(1).max(10), overall: z.number().min(1).max(10)}).strict(),
  weaknesses: z.array(z.object({view: z.string().max(30), problem: z.string().max(240), component: z.string().max(60).optional()}).strict()).max(6),
  /** At most three natural-language edits, each runnable through the normal edit path. */
  improvements: z.array(z.string().max(200)).max(3),
}).strict();
export type Review = z.infer<typeof reviewSchema>;

export const REVIEW_PROMPT = `You are reviewing four renders (arrival, aerial, garden, poolside) of a real 3D house generated by software, a flat-site contemporary Caribbean luxury villa.
Judge only what you can see: proportions, roof forms, entrance, glazing composition, materials, outdoor living, landscaping. Score 1-10. List concrete weaknesses with the component you believe is responsible.
Suggest at most 3 improvements as short imperative edit instructions about ONE architectural component each (e.g. "Make the veranda roof deeper"). Do not suggest hillside, grading or terrain changes.`;

export const MAX_REFINEMENTS = 3;
