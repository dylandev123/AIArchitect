import { expect, it, vi, afterEach } from 'vitest';
import { readFileSync } from 'node:fs';
import { applySceneOperations, validateScene } from './scene/model';
import { stageSceneReviewEdit } from './visual-review';
import { compareSceneEvidence } from './scene/visualEvidence';
import { designLessonKnowledge } from './design-learning-knowledge';
import { validateDesignLesson, summarizeLesson, learningContext } from './design-learning';
import { retrieveArchitecturalKnowledge } from '@/lib/library/architecture/retrieval';
const read=(p:string)=>JSON.parse(readFileSync(p,'utf8'));
const source='docs/architecture/spatial-root-cause/7702f28d-6098-4bf4-b08a-b12fc68ae93b.scene.json';
const before=validateScene(read(source));
const operations=[{op:'resize',id:'pool-terrace',size:[18,.2,4.5]},{op:'move',id:'pool-terrace',at:[0,.1,-7.25]}];
const output={name:before.name,summary:'Offline deterministic pool-footprint correction, not a model assessment',unsupported:[],operations};
const scope=['element:pool-terrace'];
const shots=read('docs/villa-playground/reference-review/before-captures.json');
const captures=Array.isArray(shots)?shots:shots.captures;
const transferable={title:'Reserve pool water before composing adjacent dry terraces',context:'Caribbean beachfront homes with a pool and adjacent terrace',problem:'An uninterrupted terrace slab crosses the visible water footprint.',rootCause:'The slab and water footprints overlap in plan.',correction:'Shorten and reposition the dry terrace outside the reserved water footprint.',rationale:'A distinct dry approach preserves water and avoids an unbroken slab through the pool.',exceptions:'Does not establish pool depth, safe access, circulation, structural design or architectural quality.',confidence:'high' as const,tags:['pool','terrace','caribbean']};
afterEach(()=>vi.restoreAllMocks());
it('links retained $10m geometry findings to bounded operations and preserves the original',()=>{
 const baseline=JSON.stringify(before);
 const staged=stageSceneReviewEdit(before,output.summary,output,scope);
 const comparison=compareSceneEvidence(before,staged.scene);
 expect(comparison.resolved.some(i=>i.rule.includes('water'))).toBe(true);
 expect(comparison.introduced).toEqual([]);
 expect(comparison.changedElementIds).toEqual(['pool-terrace']);
 expect(JSON.stringify(before)).toBe(baseline);
 expect(()=>stageSceneReviewEdit(before,'outside scope',output,['element:main-roof'])).toThrow(/scope/);
 expect(()=>stageSceneReviewEdit(before,'terrain',{...output,operations:[...operations,{op:'set-terrain',terrain:null}]},scope)).toThrow(/scope/);
});
it('replays evidence, blocks proposed/mocked lessons and retrieves only authorized knowledge',()=>{
 const after=applySceneOperations(before,operations);
 const lesson=validateDesignLesson({version:1,brief:'$10m Caribbean beachfront house with pool terrace',verdict:'improved',feedback:'Offline simulated reviewer judgment for contract testing only; not genuine approval.',before,after,beforeCaptures:captures,afterCaptures:captures,origin:'terra',correction:{operations,weaknesses:[transferable.problem],scope},transferable});
 const draft=designLessonKnowledge(lesson,'offline-fixture');
 expect(draft.status).toBe('proposed');
 expect(learningContext([summarizeLesson(lesson)],lesson.brief)).toBe('');
 const revision={...draft,version:1,updatedAt:'2026-10-28T00:00:00Z'};
 expect(retrieveArchitecturalKnowledge([revision],lesson.brief).selected).toEqual([]);
 const approved={...revision,status:'approved' as const,review:'Simulated authorized approval in isolated test only'};
 expect(retrieveArchitecturalKnowledge([approved],lesson.brief).selected.map(e=>e.id)).toContain(draft.id);
 expect(retrieveArchitecturalKnowledge([approved],'Compact snowy cabin without pool').selected).toEqual([]);
 expect(designLessonKnowledge({...lesson,transferable:{...transferable,title:transferable.title.toUpperCase()}},'duplicate-fixture').id).toBe(draft.id);
 expect(()=>validateDesignLesson({...lesson,origin:'mock'})).toThrow(/non-mock/);
 expect(()=>validateDesignLesson({...lesson,correction:{...lesson.correction,operations:[{op:'finish',id:'main-roof',material:'ivory'}]}})).toThrow(/reproduce/);
});
it('persists in the existing brain and applies approvals, conflicts and supersession during normal request assembly',async()=>{
 const {mkdtemp,readFile,rm}=await import('node:fs/promises');
 const {tmpdir}=await import('node:os');const path=await import('node:path');
 const root=await mkdtemp(path.join(tmpdir(),'terra-visual-learning-'));
 const originalCwd=process.cwd();
 vi.stubEnv('AI_LIBRARY_PATH',path.join(root,'library.json'));vi.stubEnv('DATABASE_URL','');vi.stubEnv('POSTGRES_URL','');
 vi.spyOn(process,'cwd').mockReturnValue(root);
 vi.stubGlobal('fetch',()=>{throw Error('Network forbidden in offline verification');});
 try{
  const {saveDesignLesson}=await import('./design-learning-store');
  const {importArchitecturalKnowledge,inspectArchitecturalKnowledge}=await import('@/lib/library/architecture/service');
  const {architecturalRequestContext}=await import('./scene/knowledgeContext');
  const after=applySceneOperations(before,operations);
  const payload={version:1,brief:'$10m Caribbean beachfront house with pool terrace',verdict:'improved',feedback:'SIMULATED approval in temporary offline store; never real human approval.',before,after,beforeCaptures:captures,afterCaptures:captures,origin:'terra',correction:{operations,weaknesses:[transferable.problem],scope},transferable};
  const saved=await saveDesignLesson(payload);
  expect(saved.knowledge?.status).toBe('proposed');
  const {createFileBackend}=await import('@/lib/library/store');
  const fresh=await createFileBackend(path.join(root,'library.json')).read();
  expect(fresh.designLessons?.find(r=>r.id===saved.id)?.lesson.correction?.operations).toEqual(operations);
  const {listDesignLessonSummaries}=await import('./design-learning-store');
  expect(await listDesignLessonSummaries()).toHaveLength(1);
  expect(JSON.parse(await readFile(path.join(root,'.data/villa-design-lessons',saved.id+'.json'),'utf8')).lesson.correction.operations).toEqual(operations);
  const query={mode:'generate' as const,prompt:payload.brief};
  expect((await architecturalRequestContext(query)).system).not.toContain(transferable.title);
  const records=await inspectArchitecturalKnowledge();const draft=records.find(r=>r.id===saved.knowledge!.id)!.revisions.at(-1)!;
  const {version,updatedAt,...entry}=draft;void updatedAt;
  await importArchitecturalKnowledge([{entry:{...entry,status:'approved',review:'SIMULATED authorized review of evidence in temporary store only'},expectedVersion:version}]);
  expect((await architecturalRequestContext(query)).system).toContain(transferable.title);
  const duplicate=await saveDesignLesson({...payload,transferable:{...transferable,correction:'Conflicting proposed advice must remain retained for consolidation, never overwrite the approved record.'}});
  expect(duplicate.knowledge?.status).toBe('needs-consolidation');
  expect((await inspectArchitecturalKnowledge()).filter(r=>r.id===draft.id)).toHaveLength(1);
  expect((await architecturalRequestContext(query)).system).not.toContain('Conflicting proposed advice');
  await expect(importArchitecturalKnowledge([{entry,expectedVersion:version}])).rejects.toThrow(/Version conflict/);
  const superseding={...entry,id:'reviewed-pool-supersession-test',title:'Revised pool terrace footprint experience',status:'approved' as const,review:'Simulated consolidation after examining both records',supersedes:[entry.id]};
  await importArchitecturalKnowledge([{entry:superseding,expectedVersion:0}]);
  const next=await architecturalRequestContext(query);
  expect(next.trace.selected.map(r=>r.id)).toContain(superseding.id);
  expect(next.trace.selected.map(r=>r.id)).not.toContain(entry.id);
 }finally{vi.restoreAllMocks();vi.unstubAllEnvs();vi.unstubAllGlobals();expect(process.cwd()).toBe(originalCwd);await rm(root,{recursive:true,force:true});}
});
it('can revise roof geometry and coordinate replacement/addition through existing Redesign operations',()=>{
 const roof=before.elements.find(e=>e.id==='main-roof')!;
 const refine=stageSceneReviewEdit(before,'Widen the roof to improve its shelter relationship',{...output,operations:[{op:'resize',id:roof.id,size:[15.4,.3,11]}]},['element:main-roof']);
 expect(refine.scene.elements.find(e=>e.id===roof.id)!.size[0]).toBe(15.4);
 const redesignOutput={...output,architecturalPlan:before.architecturalPlan,operations:[{op:'replace',id:roof.id,element:{...roof,size:[15.4,.3,11]}},{op:'add',element:{...roof,id:'review-entry-roof',at:[0,3.55,6],size:[4,.2,2]}}]};
 const staged=stageSceneReviewEdit(before,'Coordinate the main roof and arrival shelter',redesignOutput,['element:main-roof','element:review-entry-roof'],'redesign');
 expect(staged.scene.elements.some(e=>e.id==='review-entry-roof')).toBe(true);
 expect(()=>stageSceneReviewEdit(before,'Unapproved recomposition',redesignOutput,['element:main-roof','element:review-entry-roof'],'refine')).toThrow(/Redesign/);
});
