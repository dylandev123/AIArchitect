import {afterEach,expect,it,vi} from 'vitest';
import {fullPropertyBlueprint} from '@/lib/v3/parity/fullPropertyBlueprint';
import {constructV3ArchitecturalBlueprint,planV3ArchitecturalBlueprint} from '@/lib/v3/architecturalBlueprint';
import {BLANK_V3_SCENE,compileV3Scene} from '@/lib/v3/scene';
import {executeV3SceneOperations} from '@/lib/v3/operations';

afterEach(()=>vi.unstubAllGlobals());
it('atomically persists draft status, geometry and object diagnostics, reopens, repairs and promotes; rejects replacement and invalid commits',async()=>{
  const data=new Map<string,string>();
  const localStorage={getItem:(k:string)=>data.get(k)??null,setItem:(k:string,v:string)=>void data.set(k,v),removeItem:(k:string)=>void data.delete(k)};
  vi.stubGlobal('localStorage',localStorage);vi.stubGlobal('window',{localStorage,addEventListener:()=>{}});
  vi.resetModules();
  const {useProjectStore,PROJECT_STORAGE_KEY}=await import('../useProjectStore');
  const bp=fullPropertyBlueprint();bp.doors[0].offset=.1;
  const built=constructV3ArchitecturalBlueprint(planV3ArchitecturalBlueprint(bp,{buildFirst:true}).approval!);
  expect(built.outcome).toBe('draft');
  const legacy=useProjectStore.getState().createProject('Legacy textarea','house','v2-architectural');
  expect(()=>useProjectStore.getState().updateHouseConfig(legacy.id,'{')).not.toThrow();
  const store=useProjectStore.getState(),project=store.createProject('Offline draft proof','house','v3-scene');
  store.appendVersion(project.id,'Draft — Needs Refinement',JSON.stringify({...BLANK_V3_SCENE,v3Scene:built.scene}),'ai-initial-generation');
  const saved=JSON.parse(data.get(PROJECT_STORAGE_KEY)!).state.projects.find((p:{id:string})=>p.id===project.id);
  const scene=JSON.parse(saved.houseConfigJson).v3Scene;
  expect(scene.metadata.architecturalValidation.status).toBe('draft');
  expect(scene.metadata.architecturalValidation.diagnostics.some((f:{targetIds:string[]})=>f.targetIds.includes('service-door'))).toBe(true);
  expect(saved.versions.at(-1).houseConfigJson).toBe(saved.houseConfigJson);
  expect(compileV3Scene(scene)).toEqual(compileV3Scene(built.scene!));
  vi.resetModules();
  const reopened=(await import('../useProjectStore')).useProjectStore;
  const repair=executeV3SceneOperations(scene,{intent:'Correct service opening',operations:[{op:'setDoor',door:{...scene.interior.doors[0],offset:3}}]});
  expect(repair.ok).toBe(true);
  reopened.getState().appendVersion(project.id,'Complete',JSON.stringify({...BLANK_V3_SCENE,v3Scene:repair.scene}));
  const complete=reopened.getState().getProject(project.id)!;
  expect(JSON.parse(complete.houseConfigJson).v3Scene.metadata.architecturalValidation.status).toBe('complete');
  const snapshot=JSON.stringify(complete),persisted=data.get(PROJECT_STORAGE_KEY);
  expect(()=>reopened.getState().appendVersion(project.id,'Unintended draft overwrite',saved.houseConfigJson,'ai-initial-generation')).toThrow(/cannot replace/);
  const broken=JSON.parse(complete.houseConfigJson);broken.v3Scene.objects.shift();
  expect(()=>reopened.getState().updateHouseConfig(project.id,JSON.stringify(broken))).toThrow();
  expect(JSON.stringify(reopened.getState().getProject(project.id))).toBe(snapshot);
  expect(data.get(PROJECT_STORAGE_KEY)).toBe(persisted);
  const markerRemoved=JSON.parse(complete.houseConfigJson);delete markerRemoved.v3Scene.metadata.architecturalValidation;
  reopened.getState().updateHouseConfig(project.id,JSON.stringify(markerRemoved));
  expect(JSON.parse(reopened.getState().getProject(project.id)!.houseConfigJson).v3Scene.metadata.architecturalValidation.status).toBe('complete');
},20000);
