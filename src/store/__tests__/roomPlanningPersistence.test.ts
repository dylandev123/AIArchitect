import {afterEach,it,expect,vi} from 'vitest';
import {relationshipGardenHome} from '@/lib/v3/parity/roomPlanning';
import {preparePlanEvaluation,checkoutPlanEvaluation,reviseDraftRoomLayout} from '@/lib/v3/architecturalPlanEvaluation';
import {BLANK_V3_SCENE} from '@/lib/v3/scene';
import {executeV3SceneOperations} from '@/lib/v3/operations';
import {planConstructionBlockers} from '@/lib/v3/architecturalPlanFirst';
afterEach(()=>vi.unstubAllGlobals());
it('persists authoritative developed rooms, explicit edits and unresolved floor intent using isolated real project storage',async()=>{
 const data=new Map<string,string>();
 const sentinel={id:'existing-untouched',name:'Preserved project',generationMode:'v3-scene',houseConfigJson:JSON.stringify(BLANK_V3_SCENE),versions:[],createdAt:1,updatedAt:1};
 data.set('ai-architect-projects',JSON.stringify({state:{projects:[sentinel]},version:6}));
 const localStorage={getItem:(key:string)=>data.get(key)??null,setItem:(key:string,value:string)=>void data.set(key,value),removeItem:(key:string)=>void data.delete(key)};
 vi.stubGlobal('localStorage',localStorage);vi.stubGlobal('window',{localStorage,addEventListener:()=>{}});vi.resetModules();
 const {useProjectStore,PROJECT_STORAGE_KEY}=await import('../useProjectStore');
 const project=useProjectStore.getState().createProject('Isolated room planning','house','v3-scene');
 const stage=preparePlanEvaluation(relationshipGardenHome());
 useProjectStore.getState().appendVersion(project.id,'Developed floor',JSON.stringify({...BLANK_V3_SCENE,v3Scene:stage.scene}),'ai-plan-evaluation');
 const saved=useProjectStore.getState().getProject(project.id)!;
 const scene=JSON.parse(saved.houseConfigJson).v3Scene;
 const room=scene.interior.rooms.find((r:{id:string})=>r.id==='garden-living');
 const edited=executeV3SceneOperations(scene,{intent:'Edit the authoritative room extent',operations:[{op:'editRoom',target:room.id,room:{footprint:{...room.footprint,width:room.footprint.width-.4}}}]});
 expect(edited.ok).toBe(true);
 useProjectStore.getState().appendVersion(project.id,'Explicit room edit',JSON.stringify({...BLANK_V3_SCENE,v3Scene:edited.scene}),'v3-planning-inspector');
 const record=JSON.parse(data.get(PROJECT_STORAGE_KEY)!).state.projects.find((p:{id:string})=>p.id===project.id);
 expect(JSON.parse(record.houseConfigJson).v3Scene.interior.rooms.find((r:{id:string})=>r.id===room.id).footprint.width).toBeCloseTo(room.footprint.width-.4);
 expect(record.versions.at(-1).houseConfigJson).toBe(record.houseConfigJson);
 vi.resetModules();const reopened=(await import('../useProjectStore')).useProjectStore;
 expect(reopened.getState().getProject(project.id)!.houseConfigJson).toBe(record.houseConfigJson);
 expect(checkoutPlanEvaluation(JSON.parse(record.houseConfigJson).v3Scene).ok).toBe(true);
 const bad=relationshipGardenHome();Object.assign(bad.buildings[0].storeys[0].spaces[0],{size:{minDepth:90}});
 const draft=preparePlanEvaluation(bad),draftProject=reopened.getState().createProject('Isolated unresolved floor','house','v3-scene');
 reopened.getState().appendVersion(draftProject.id,'Unresolved intent',JSON.stringify({...BLANK_V3_SCENE,v3Scene:draft.scene}),'ai-plan-evaluation');
 const persisted=JSON.parse(reopened.getState().getProject(draftProject.id)!.houseConfigJson).v3Scene;
 expect(persisted.metadata.roomLayoutDrafts).toEqual(draft.scene!.metadata.roomLayoutDrafts);
 expect(planConstructionBlockers(checkoutPlanEvaluation(persisted)).length).toBeGreaterThan(0);
 const intention=structuredClone(persisted.metadata.roomLayoutDrafts[0]);delete intention.spaces[0].size;
 const fixed=reviseDraftRoomLayout(persisted,intention.storeyId,{spaces:intention.spaces,layout:intention.layout});expect(fixed.ok).toBe(true);
 reopened.getState().appendVersion(draftProject.id,'Developed corrected intent',JSON.stringify({...BLANK_V3_SCENE,v3Scene:fixed.scene}),'v3-planning-inspector');
 const final=JSON.parse(reopened.getState().getProject(draftProject.id)!.houseConfigJson).v3Scene;
 expect(final.metadata.roomLayoutDrafts).toEqual([]);expect(planConstructionBlockers(checkoutPlanEvaluation(final))).toEqual([]);
 const storedSentinel=JSON.parse(data.get(PROJECT_STORAGE_KEY)!).state.projects.find((p:{id:string})=>p.id===sentinel.id);
 expect(storedSentinel).toEqual(sentinel);
});
