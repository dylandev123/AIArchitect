/** Offline evidence only: no model adapter, credentials, saved projects or provider. */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { planEvaluationPrompt, planExteriorPrompt, preparePlanEvaluation, checkoutPlanEvaluation } from '../src/lib/v3/architecturalPlanEvaluation';
import { v3ArchitecturalBlueprintPrompt } from '../src/lib/v3/architecturalBlueprintGeneration';
import { splitV3ArchitecturalBlueprint, sameArchitecturalPlan } from '../src/lib/v3/architecturalPlanFirst';
import { distinctArchitecturalBlueprints } from '../src/lib/v3/parity/architecturalBlueprint';
import { DEFAULT_PRICING } from '../src/lib/ai/pricing';

globalThis.fetch = async () => { throw Error('Network forbidden during architectural evidence capture'); };
const out = 'docs/architecture/architectural-blueprint-pipeline/terra-intelligence';
mkdirSync(out, { recursive: true });
const sha = (raw: string) => createHash('sha256').update(raw).digest('hex');
const prompts = Object.fromEntries(Object.entries({ plan: planEvaluationPrompt(), fullProperty: v3ArchitecturalBlueprintPrompt(), exterior: planExteriorPrompt() }).map(([name, prompt]) => {
  const start = prompt.indexOf('{'), schema = JSON.parse(prompt.slice(start));
  writeFileSync(`${out}/${name}-prompt.txt`, prompt);
  return [name, { bytes: Buffer.byteLength(prompt), instructionBytes: Buffer.byteLength(prompt.slice(0, start)), schemaBytes: Buffer.byteLength(prompt.slice(start)), roughTokensAtFourChars: Math.ceil(prompt.length / 4), required: schema.required, sha256: sha(prompt) }];
}));

const histories = ['2026-10-20', '2026-10-21'].map(date => {
  const file = `src/lib/v3/__tests__/fixtures/architectural-blueprint-live-${date}.json`;
  const raw = readFileSync(file, 'utf8'), blueprint = JSON.parse(raw);
  const input = splitV3ArchitecturalBlueprint(blueprint).plan, before = JSON.stringify(input);
  const checked = preparePlanEvaluation(input);
  if (!checked.ok || !checked.scene) throw Error(`Recovered ${date} plan failed: ${JSON.stringify(checked.findings)}`);
  const reloaded = checkoutPlanEvaluation(JSON.parse(JSON.stringify(checked.scene)));
  if (!reloaded.ok || !reloaded.scene || !sameArchitecturalPlan(checked.scene, reloaded.scene)) throw Error(`Recovered ${date} checkout drift`);
  if (JSON.stringify(input) !== before || readFileSync(file, 'utf8') !== raw) throw Error('Recovered input changed');
  return { file, sha256: sha(raw), bytes: Buffer.byteLength(raw), concept: blueprint.concept, character: blueprint.character, site: blueprint.site,
    buildings: input.buildings.map(b => ({ id: b.id, plan: b.plan, location: b.location, storeyHeights: b.storeys.map(s => s.height), rooms: b.storeys.reduce((n, s) => n + s.spaces.length, 0), exteriorAssemblies: blueprint.buildings.find((e: {id: string}) => e.id === b.id).facade.assemblies?.length ?? 0 })),
    features: input.features.map(f => ({ id: f.id, type: f.type })), planAccepted: checked.ok, inputUnchanged: true, samePlanAfterReload: true,
    diagnostics: [...new Set(checked.findings.map(f => f.code))],
    provenance: 'Recovered pre-existing provider design, explicitly split into plan/exterior offline. Not generated by the revised instructions.',
  };
});
const freedoms = distinctArchitecturalBlueprints().map(({name, blueprint}) => {
  const result = preparePlanEvaluation(splitV3ArchitecturalBlueprint(blueprint).plan);
  if (!result.ok) throw Error(`${name}: ${JSON.stringify(result.findings)}`);
  return { name, accepted: true, kinds: blueprint.buildings.map(b => b.plan.kind), provenance: 'Hand-authored offline fixture, never a runtime template or evidence of Terra creativity' };
});
const price = DEFAULT_PRICING['gpt-5.6-terra'];
const cost = (input: number, output: number) => (input * price.input + output * price.output) / 1e6;
const evidence = { providerCalls: 0, paidGenerations: 0, date: '2026-10-21', timezone: 'America/St_Lucia', prompts, histories, freedoms,
  pricing: { source: 'Repository DEFAULT_PRICING; not verified provider billing', perMillionTokens: price,
    examples: { onePlan: { input: 5000, output: 6000, usd: cost(5000,6000) }, threeSequentialCalls: { input: 21000, output: 14000, usd: cost(21000,14000) }, laterExterior: { input: 9000, output: 6000, usd: cost(9000,6000) } },
    caveat: 'Illustrative uncached totals, not measured revised-model tokens or a guaranteed cap. Reasoning tokens, retransmitted plans and provider defaults may change usage.' },
};
writeFileSync(`${out}/evidence.json`, JSON.stringify(evidence, null, 2) + '\n');
console.log(JSON.stringify({ providerCalls: 0, prompts, recoveredPlans: histories.map(h => ({ file: h.file, sha256: h.sha256, accepted: h.planAccepted })), freedoms, pricing: evidence.pricing }, null, 2));
